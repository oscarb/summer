package se.oscarb.summer.util

import android.app.Activity
import android.content.Intent
import android.net.Uri

/**
 * Utility to identify whether an incoming URL or Activity intent originated from
 * Google Discover / Google Feed (e.g. via shorteners, tracking params, or intent referrer).
 */
object GoogleFeedDetector {

  const val GOOGLE_APP_PACKAGE = "com.google.android.googlequicksearchbox"

  // Google shortener domains used in Discover / Google App
  private val GOOGLE_FEED_SHORTENER_HOSTS = setOf(
    "search.app",
    "share.google"
  )

  /**
   * Evaluates whether an incoming intent was launched from Google Feed / Discover.
   *
   * Checks multiple signals:
   * 1. Activity referrer package (com.google.android.googlequicksearchbox) or EXTRA_REFERRER.
   * 2. URL hostname matching Google's Discover link shorteners (`search.app`, `share.google`).
   * 3. Google tracking/routing query parameters or redirect wrappers:
   *    - `usqp`: Universal Search Query Parameter used on Discover/Google App cards.
   *    - `ved`: Visual Element Data click-tracking parameter generated by Google surfaces.
   *    - `google.com/url` redirect wrapper.
   */
  fun isFromGoogleFeed(intent: Intent?, url: String?, referrer: Uri?): Boolean {
    // 1. Check intent source referrer (Android Activity referrer)
    if (isGoogleAppReferrer(referrer)) {
      return true
    }

    // 2. Check Intent.EXTRA_REFERRER or Intent.EXTRA_REFERRER_NAME directly if present in extras
    val extraReferrer = if (android.os.Build.VERSION.SDK_INT >= android.os.Build.VERSION_CODES.TIRAMISU) {
      intent?.getParcelableExtra(Intent.EXTRA_REFERRER, Uri::class.java)
    } else {
      @Suppress("DEPRECATION")
      intent?.getParcelableExtra(Intent.EXTRA_REFERRER)
    } ?: intent?.getStringExtra(Intent.EXTRA_REFERRER_NAME)?.let { runCatching { Uri.parse(it) }.getOrNull() }
    if (isGoogleAppReferrer(extraReferrer)) {
      return true
    }

    // 3. Check URL structure (shortener domains and query parameters)
    return isGoogleFeedUrl(url)
  }

  /**
   * Checks if the referrer URI points to the Google App.
   */
  fun isGoogleAppReferrer(referrer: Uri?): Boolean {
    if (referrer == null) return false
    return isGoogleAppReferrerString(referrer.toString())
  }

  fun isGoogleAppReferrerString(referrerStr: String?): Boolean {
    if (referrerStr.isNullOrBlank()) return false
    return referrerStr.contains(GOOGLE_APP_PACKAGE, ignoreCase = true)
  }

  /**
   * Checks if the URL matches Google feed shorteners or distinctive Google tracking parameters.
   */
  fun isGoogleFeedUrl(rawUrl: String?): Boolean {
    if (rawUrl.isNullOrBlank()) return false
    val uri = runCatching { java.net.URI(rawUrl) }.getOrNull()
    val host = (uri?.host ?: runCatching { Uri.parse(rawUrl).host }.getOrNull())?.lowercase() ?: return false

    // 1. Shortener domains (Google App "Shorten links to web pages" feature)
    if (GOOGLE_FEED_SHORTENER_HOSTS.any { host == it || host.endsWith(".$it") }) {
      return true
    }

    // 2. Google redirect links (e.g. google.com/url?...)
    val path = uri?.path ?: runCatching { Uri.parse(rawUrl).path }.getOrNull()
    if ((host == "google.com" || host.endsWith(".google.com")) && path == "/url") {
      return true
    }

    // 3. Characteristic query parameters attached to links clicked in Google Feed / Search:
    // - `usqp`: Universal search query parameter for mobile Discover / Search cards
    // - `ved`: Visual Element Data click tracking token
    val query = uri?.rawQuery ?: runCatching { Uri.parse(rawUrl).query }.getOrNull() ?: ""
    if (query.isNotEmpty()) {
      val params = query.split("&").map { it.substringBefore("=") }
      if (params.contains("usqp") || params.contains("ved")) {
        return true
      }
    }

    return false
  }
}
